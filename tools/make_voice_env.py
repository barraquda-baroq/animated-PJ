"""Mouth-openness envelopes for lip-sync, from the final dialogue takes.

  python3 tools/make_voice_env.py      (after audio/voice_takes.py and tools/make_timeline.py)
Writes pv/engine/lib/anime_voice.js:
  PV.voiceEnv = [{id, speaker, t0, fps, v:[0..1 ...]}]   (t0 = global timeline seconds of the first value)
Values are a speech-band envelope (250-3500 Hz), normalised per line, at 24 per second.
"""
import json, os, sys
import numpy as np
from scipy.signal import butter, sosfiltfilt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'audio'))
import dsp  # noqa: E402

FPS = 24


def env(path):
    x = dsp.mono(dsp.load(path))
    sos = butter(4, [250, 3500], btype='band', fs=dsp.SR, output='sos')
    y = np.abs(sosfiltfilt(sos, x))
    hop = dsp.SR // FPS
    n = int(np.ceil(len(y) / hop))
    e = np.array([np.sqrt(np.mean(y[i * hop:(i + 1) * hop] ** 2)) if i * hop < len(y) else 0.0 for i in range(n)])
    if e.max() <= 0:
        return e
    e = e / np.percentile(e[e > 0], 95)
    e = np.clip((e - 0.08) / 0.92, 0, 1) ** 0.7     # gate the breath floor, open quickly
    return np.round(e, 2)


def main():
    cues = json.load(open(os.path.join(ROOT, 'audio', 'cues.json'), encoding='utf-8'))
    out = []
    for v in cues['voice']:
        p = os.path.join(ROOT, 'audio', 'voice_out', f"{v['id']}.wav")
        if not os.path.exists(p):
            continue
        e = env(p)
        out.append({'id': v['id'], 'speaker': v['speaker'], 't0': round(v['start'] + v.get('offset', 0.0), 3), 'fps': FPS,
                    'v': [float(a) for a in e]})
    js = ('// generated by tools/make_voice_env.py — lip-sync envelopes of the final dialogue takes (global seconds)\n'
          'window.PV = window.PV || {};\nPV.voiceEnv = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    with open(os.path.join(ROOT, 'pv', 'engine', 'lib', 'anime_voice.js'), 'w', encoding='utf-8') as f:
        f.write(js)
    print(len(out), 'lines,', sum(len(o['v']) for o in out), 'values')


if __name__ == '__main__':
    main()
